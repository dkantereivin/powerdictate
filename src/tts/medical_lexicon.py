def register_medical_lexicon(pipeline) -> int:
    """
    Registers the medical phonetic overrides directly into the Kokoro/Misaki G2P lexicon.
    Returns the number of overridden terms.
    """
    if not hasattr(pipeline, "g2p") or not hasattr(pipeline.g2p, "lexicon"):
        return 0

    lex = pipeline.g2p.lexicon
    if not hasattr(lex, "golds") or not isinstance(lex.golds, dict):
        return 0

    count = 0
    for term, phonemes in MEDICAL_GOLDS.items():
        lex.golds[term.lower()] = phonemes
        count += 1

    return count
